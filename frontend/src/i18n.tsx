const dict: Record<Lang, Record<string, string>> = { en, id, ar };

type I18n = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
  isRTL: boolean;
  align: 'left' | 'right';
  row: 'row' | 'row-reverse';
};

const Ctx = createContext<I18n | undefined>(undefined);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>('en');

  useEffect(() => {
    storeGet(KEY).then((v) => {
      if (v === 'en' || v === 'id' || v === 'ar') setLangState(v);
    });
  }, []);

  const setLang = (l: Lang) => {
    setLangState(l);
    storeSet(KEY, l);
  };

  const value = useMemo<I18n>(() => {
    const isRTL = lang === 'ar';
    return {
      lang,
      setLang,
      isRTL,
      align: isRTL ? 'right' : 'left',
      row: isRTL ? 'row-reverse' : 'row',
      t: (key, vars) => {
        let out = dict[lang][key] ?? dict.en[key] ?? key;
        if (vars) Object.entries(vars).forEach(([k, v]) => (out = out.replace(`{${k}}`, String(v))));
        return out;
      },
    };
  }, [lang]);

  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n() {
  const ctx = useContext(Ctx);
  if (!ctx) throw new Error('useI18n outside I18nProvider');
  return ctx;
}
